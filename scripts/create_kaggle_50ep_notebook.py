    "# Cell 5: SpriteDeformationNet Model with Dual-GPU DataParallel Wrapper\n",
    "def conv_block(cin, cout):\n",
    "    groups = next((g for g in (8, 4, 2, 1) if cout % g == 0), 1)\n",
    "    return nn.Sequential(\n",
    "        nn.Conv2d(cin, cout, 3, padding=1), nn.GroupNorm(groups, cout), nn.SiLU(),\n",
    "        nn.Conv2d(cout, cout, 3, padding=1), nn.GroupNorm(groups, cout), nn.SiLU()\n",
    "    )\n",
    "\n",
    "class SpriteDeformationNet(nn.Module):\n",
    "    \"\"\"Predicts dense 2D optical sampling flow field for pixel-art sprite warping.\"\"\"\n",
    "    def __init__(self, base=32, max_flow=0.30):\n",
    "        super().__init__()\n",
    "        self.max_flow = max_flow\n",
    "        self.enc0 = conv_block(5, base)  # 3 RGB + 2 Conditioning channels\n",
    "        self.down1 = nn.Conv2d(base, base * 2, 4, 2, 1)\n",
    "        self.enc1 = conv_block(base * 2, base * 2)\n",
    "        self.down2 = nn.Conv2d(base * 2, base * 4, 4, 2, 1)\n",
    "        self.mid = conv_block(base * 4, base * 4)\n",
    "        self.up1 = nn.ConvTranspose2d(base * 4, base * 2, 4, 2, 1)\n",
    "        self.dec1 = conv_block(base * 4, base * 2)\n",
    "        self.up0 = nn.ConvTranspose2d(base * 2, base, 4, 2, 1)\n",
    "        self.dec0 = conv_block(base * 2, base)\n",
    "        self.flow_head = nn.Conv2d(base, 2, 3, padding=1)\n",
    "        nn.init.zeros_(self.flow_head.weight)\n",
    "        nn.init.zeros_(self.flow_head.bias)\n",
    "\n",
    "    def forward(self, source, condition):\n",
    "        x0 = self.enc0(torch.cat([source, condition], dim=1))\n",
    "        x1 = self.enc1(self.down1(x0))\n",
    "        x2 = self.mid(self.down2(x1))\n",
    "        y1 = self.up1(x2)\n",
    "        if y1.shape[-2:] != x1.shape[-2:]:\n",
    "            y1 = F.interpolate(y1, size=x1.shape[-2:], mode=\"nearest\")\n",
    "        y1 = self.dec1(torch.cat([y1, x1], dim=1))\n",
    "        y0 = self.up0(y1)\n",
    "        if y0.shape[-2:] != x0.shape[-2:]:\n",
    "            y0 = F.interpolate(y0, size=x0.shape[-2:], mode=\"nearest\")\n",
    "        flow = torch.tanh(self.flow_head(self.dec0(torch.cat([y0, x0], dim=1)))) * self.max_flow\n",
    "\n",
    "        b, _, h, w = source.shape\n",
    "        yy, xx = torch.meshgrid(\n",
    "            torch.linspace(-1, 1, h, device=source.device, dtype=source.dtype),\n",
    "            torch.linspace(-1, 1, w, device=source.device, dtype=source.dtype),\n",
    "            indexing=\"ij\"\n",
    "        )\n",
    "        grid = torch.stack([xx, yy], dim=-1).unsqueeze(0).expand(b, -1, -1, -1)\n",
    "        warped = F.grid_sample(source, grid + flow.permute(0, 2, 3, 1),\n",
    "                               mode=\"nearest\", padding_mode=\"zeros\", align_corners=True)\n",
    "        return warped, flow\n",
