    "# Cell 4: Conditional Diffusion UNet Architecture & Forward Noise Scheduler\n",
    "class SinusoidalTimeEmbedding(nn.Module):\n",
    "    def __init__(self, dim):\n",
    "        super().__init__()\n",
    "        self.dim = dim\n",
    "\n",
    "    def forward(self, time):\n",
    "        device = time.device\n",
    "        half_dim = self.dim // 2\n",
    "        embeddings = math.log(10000) / (half_dim - 1)\n",
    "        embeddings = torch.exp(torch.arange(half_dim, device=device) * -embeddings)\n",
    "        embeddings = time[:, None] * embeddings[None, :]\n",
    "        embeddings = torch.cat((embeddings.sin(), embeddings.cos()), dim=-1)\n",
    "        return embeddings\n",
    "\n",
    "class ConditionalDiffusionUNet(nn.Module):\n",
    "    \"\"\"Image-conditioned diffusion UNet taking noisy target (3ch), time (1ch), and 4-view reference (3ch).\"\"\"\n",
    "    def __init__(self, in_channels=6, out_channels=3, base=64, time_dim=128):\n",
    "        super().__init__()\n",
    "        self.time_mlp = nn.Sequential(\n",
    "            SinusoidalTimeEmbedding(time_dim),\n",
    "            nn.Linear(time_dim, time_dim),\n",
    "            nn.SiLU()\n",
    "        )\n",
    "        \n",
    "        # Encoder: Concat [noisy_target (3) + reference_image (3)] = 6 channels\n",
    "        self.in_conv = nn.Conv2d(in_channels, base, 3, padding=1)\n",
    "        self.down1 = nn.Conv2d(base, base * 2, 4, 2, 1)\n",
    "        self.time_emb1 = nn.Linear(time_dim, base * 2)\n",
    "        \n",
    "        self.down2 = nn.Conv2d(base * 2, base * 4, 4, 2, 1)\n",
    "        self.time_emb2 = nn.Linear(time_dim, base * 4)\n",
    "        \n",
    "        # Bottleneck\n",
    "        self.mid_conv = nn.Conv2d(base * 4, base * 4, 3, padding=1)\n",
    "        \n",
    "        # Decoder\n",
    "        self.up1 = nn.ConvTranspose2d(base * 4, base * 2, 4, 2, 1)\n",
    "        self.up2 = nn.ConvTranspose2d(base * 2, base, 4, 2, 1)\n",
    "        self.out_conv = nn.Conv2d(base, out_channels, 3, padding=1)\n",
    "        \n",
    "    def forward(self, noisy_target, timestep, reference):\n",
    "        t_emb = self.time_mlp(timestep)\n",
    "        x = torch.cat([noisy_target, reference], dim=1) # 6 channels\n",
    "        \n",
    "        h0 = F.silu(self.in_conv(x))\n",
    "        h1 = F.silu(self.down1(h0) + self.time_emb1(t_emb)[:, :, None, None])\n",
    "        h2 = F.silu(self.down2(h1) + self.time_emb2(t_emb)[:, :, None, None])\n",
    "        \n",
    "        m = F.silu(self.mid_conv(h2))\n",
    "        \n",
    "        u1 = F.silu(self.up1(m) + h1)\n",
    "        u2 = F.silu(self.up2(u1) + h0)\n",
    "        \n",
    "        return self.out_conv(u2) # Predicted noise epsilon\n",
    "\n",
    "# Forward Diffusion Math (Linear Beta Schedule)\n",
    "TIMESTEPS = 1000\n",
    "betas = torch.linspace(1e-4, 0.02, TIMESTEPS).to(DEVICE)\n",
    "alphas = 1.0 - betas\n",
    "alphas_cumprod = torch.cumprod(alphas, dim=0).to(DEVICE)\n",
    "\n",
    "raw_model = ConditionalDiffusionUNet().to(DEVICE)\n",
